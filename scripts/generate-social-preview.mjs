#!/usr/bin/env node
// Makes this project's deployment link unfurl into a card when it is pasted into
// a chat: it publishes the og profile shot as the site's preview image and keeps
// the Open Graph / Twitter tags in the page head in sync with the metadata.
//
// Usage:
//   npm run social          # copy the image and update the tags
//   npm run social:check    # non-zero exit if either is missing or stale
//
// The image comes from ./project-media/og.jpg (npm run shots). Paths for the
// page head and the static directory live in the `social` block of
// ./project-meta.config.mjs, because every project puts them somewhere else.
//
// Installed by the portfolio meta toolkit; edit the template there.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, URL } from 'node:url';

import config from './project-meta.config.mjs';

const START = '<!-- project-meta:social:start (generated by scripts/generate-social-preview.mjs) -->';
const END = '<!-- project-meta:social:end -->';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const checkOnly = process.argv.includes('--check');

const social = config.social ?? {};
const curated = config.curated ?? {};
const deploymentUrl = curated.deploymentUrl;

if (!social.htmlFile && !social.renderedFrom) {
  console.log('[social] ' + config.slug + ': no htmlFile configured - this project renders its head from code.');
  console.log('         Set social.htmlFile in scripts/project-meta.config.mjs, or add the tags in the framework head.');
  process.exit(0);
}
if (!deploymentUrl) {
  console.log('[social] ' + config.slug + ': no deploymentUrl, so a preview card has nowhere to point. Skipping.');
  process.exit(0);
}

const htmlPath = social.htmlFile ? path.join(repoRoot, social.htmlFile) : null;
if (htmlPath && !fs.existsSync(htmlPath)) {
  console.error('[social] ' + config.slug + ': ' + social.htmlFile + ' does not exist.');
  process.exit(1);
}

const imageName = social.imageName ?? 'og-image.jpg';
const imageUrlPath = social.imageUrlPath ?? '/' + imageName;
const staticDir = social.staticDir ? path.join(repoRoot, social.staticDir) : repoRoot;
const targetImage = path.join(staticDir, imageName);
const sourceImage = path.join(repoRoot, social.sourceImage ?? path.join('project-media', 'og.jpg'));

const origin = new URL(deploymentUrl).origin;
const imageUrl = origin + imageUrlPath;
const pageUrl = deploymentUrl;
const title = social.title ?? curated.title ?? config.slug;
// Cards show two or three lines: prefer the full description, trimmed on a word.
const description = social.description ?? summarize(curated.description) ?? curated.subtitle ?? '';
const siteName = social.siteName ?? title;

// The browser-tab title and the plain description meta are part of the same
// story as the card, so they are managed here too: social.pageTitle names the
// tab (default: the curated title), the description meta repeats the card's.
const pageTitle = social.pageTitle ?? title;

const tags = [
  START,
  tag('name', 'description', description),
  tag('property', 'og:type', 'website'),
  tag('property', 'og:site_name', siteName),
  tag('property', 'og:title', title),
  tag('property', 'og:description', description),
  tag('property', 'og:url', pageUrl),
  tag('property', 'og:image', imageUrl),
  tag('property', 'og:image:secure_url', imageUrl),
  tag('property', 'og:image:type', 'image/jpeg'),
  tag('property', 'og:image:width', '1200'),
  tag('property', 'og:image:height', '630'),
  tag('property', 'og:image:alt', title + ' - ' + description),
  tag('name', 'twitter:card', 'summary_large_image'),
  tag('name', 'twitter:title', title),
  tag('name', 'twitter:description', description),
  tag('name', 'twitter:image', imageUrl),
  tag('name', 'twitter:image:alt', title + ' - ' + description),
  END
].filter(Boolean);

// A project whose head is rendered from code (Next, Nuxt, an Angular service)
// keeps its tags there; this script still publishes and checks its image.
const html = htmlPath ? fs.readFileSync(htmlPath, 'utf8') : '';
const eol = html.includes('\r\n') ? '\r\n' : '\n';
const indent = detectHeadIndent(html);
const block = tags.map((line) => indent + line).join(eol);

// Any loose description meta the page carries outside the block is superseded
// by the one inside it; the tag is matched attribute by attribute so a
// multi-line one goes too.
const attribute = String.raw`(?:[^>"']|"[^"]*"|'[^']*')*`;
const looseDescription = new RegExp(String.raw`[ \t]*<meta\b` + attribute + String.raw`\bname=["']description["']` + attribute + String.raw`>[ \t]*\r?\n?`, 'gi');
const stripped = stripOutsideBlock(html, looseDescription);

// A repo's formatter may re-wrap the generated tags (prettier puts one
// attribute per line); that is the same markup, so it is not drift.
const blockCurrent = htmlPath && stripped.includes(START) && stripped.includes(END) &&
  normalizeMarkup(stripped.slice(stripped.indexOf(START), stripped.indexOf(END) + END.length)) === normalizeMarkup(block);

let next = stripped;
if (!htmlPath || blockCurrent) {
  // nothing to inject: the head lives in code, or the block is already right
} else if (stripped.includes(START) && stripped.includes(END)) {
  // The existing block already sits at the right indentation; replace it in place.
  next = stripped.slice(0, stripped.indexOf(START)) + block.trimStart() + stripped.slice(stripped.indexOf(END) + END.length);
} else {
  const headClose = stripped.search(/<\/head>/i);
  if (headClose === -1) {
    console.error('[social] ' + config.slug + ': ' + social.htmlFile + ' has no </head> to insert into.');
    process.exit(1);
  }
  next = stripped.slice(0, headClose) + block.trimStart() + eol + indent + stripped.slice(headClose);
}
if (htmlPath) next = applyPageTitle(next);

const imageMissing = !fs.existsSync(sourceImage) && !fs.existsSync(targetImage);
const imageStale = fs.existsSync(sourceImage) &&
  (!fs.existsSync(targetImage) || fs.readFileSync(sourceImage).compare(fs.readFileSync(targetImage)) !== 0);

if (checkOnly) {
  const problems = [];
  if (htmlPath && next !== html) problems.push('head tags are out of date');
  if (imageMissing) problems.push('no preview image (run: npm run shots -- --profiles=og)');
  else if (imageStale) problems.push('published image differs from project-media/og.jpg');
  if (problems.length > 0) {
    console.error('[social] ' + config.slug + ': ' + problems.join('; '));
    process.exit(1);
  }
  console.log('[social] ' + config.slug + ': preview card is up to date (' + imageUrl + ').');
  process.exit(0);
}

if (imageMissing) {
  console.warn('[social] ' + config.slug + ': no project-media/og.jpg yet - run "npm run shots -- --profiles=og" first.');
} else if (imageStale) {
  fs.mkdirSync(staticDir, { recursive: true });
  fs.copyFileSync(sourceImage, targetImage);
  console.log('[social] ' + config.slug + ': published ' + path.relative(repoRoot, targetImage));
}

if (!htmlPath) {
  console.log('[social] ' + config.slug + ': head tags are rendered from ' + social.renderedFrom + ' - keep them in step with this metadata.');
} else if (next !== html) {
  fs.writeFileSync(htmlPath, next);
  console.log('[social] ' + config.slug + ': updated preview tags in ' + social.htmlFile);
} else {
  console.log('[social] ' + config.slug + ': preview tags already current in ' + social.htmlFile);
}
console.log('[social] ' + config.slug + ': card points at ' + imageUrl);

// Cards clip long text themselves; only a runaway description is trimmed here,
// so a two-sentence blurb reaches the reader whole.
function summarize(text, limit = 420) {
  if (!text) return undefined;
  if (text.length <= limit) return text;
  const cut = text.slice(0, limit);
  return cut.slice(0, cut.lastIndexOf(' ')).replace(/[,;:]$/, '') + '...';
}

function tag(attribute, name, content) {
  if (!content) return '';
  return '<meta ' + attribute + '="' + name + '" content="' + escapeAttribute(content) + '" />';
}

function escapeAttribute(value) {
  return String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function stripOutsideBlock(source, pattern) {
  if (!source.includes(START) || !source.includes(END)) return source.replace(pattern, '');
  const start = source.indexOf(START);
  const end = source.indexOf(END) + END.length;
  return source.slice(0, start).replace(pattern, '') + source.slice(start, end) + source.slice(end).replace(pattern, '');
}

// Sets the <title> text; a page without one gets it right before the block.
function applyPageTitle(source) {
  const escaped = escapeText(pageTitle);
  const titleTag = /<title(\s[^>]*)?>([\s\S]*?)<\/title>/i;
  const match = titleTag.exec(source);
  if (match) {
    if (match[2].trim() === escaped) return source;
    return source.slice(0, match.index) + '<title' + (match[1] ?? '') + '>' + escaped + '</title>' + source.slice(match.index + match[0].length);
  }
  const at = source.indexOf(START);
  if (at === -1) return source;
  return source.slice(0, at) + '<title>' + escaped + '</title>' + eol + indent + source.slice(at);
}

function escapeText(value) {
  return String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function normalizeMarkup(text) {
  return text.replace(/\s+/g, ' ').replace(/\s*\/>/g, ' />').trim();
}

// A head whose tags start at column 0 gets an unindented block.
function detectHeadIndent(html) {
  const match = /\n([ \t]*)<(?:meta|link|title)/i.exec(html);
  return match ? match[1] : '    ';
}
