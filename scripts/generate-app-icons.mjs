#!/usr/bin/env node
// Renders this project's icon set from one source SVG and keeps the page head
// pointing at it: favicon.ico, apple-touch-icon.png, icon-192.png,
// icon-512.png, icon-maskable-512.png and site.webmanifest.
//
// Usage:
//   npm run icons            # render the icons and refresh the head links
//   npm run icons:check      # non-zero exit if the icons or the links drifted
//
// The source is <staticDir>/favicon.svg by default. The `icons` block in
// ./project-meta.config.mjs can override any of it:
//   icons: {
//     mode: 'generate' | 'check' | 'skip',   // check: the project owns its own set
//     source: 'branding/icon.svg',           // the SVG everything is rendered from
//     outputDir: 'public',                    // where the files are written
//     urlPrefix: '/',                         // how the page reaches outputDir
//     htmlFile: 'index.html',                 // the head that carries the links
//     background: '#101010',                  // fill behind maskable/apple icons
//     themeColor: '#7aa2f7',                  // <meta name="theme-color">
//     name: 'Long name', shortName: 'Short'   // for the web manifest
//   }
//
// Chromium (via Playwright) does the rasterising, resolved from this repo or
// the portfolio checkout, so a project needs no new dependency.
//
// Installed by the portfolio meta toolkit; edit the template there.

import { Buffer } from 'node:buffer';
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

import config from './project-meta.config.mjs';

const START = '<!-- project-meta:icons:start (generated by scripts/generate-app-icons.mjs) -->';
const END = '<!-- project-meta:icons:end -->';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const checkOnly = process.argv.includes('--check');

const curated = config.curated ?? {};
const social = config.social ?? {};
const icons = config.icons ?? {};
const mode = icons.mode ?? 'generate';
const slug = config.slug;

if (mode === 'skip') {
  console.log('[icons] ' + slug + ': icons are not managed for this project (icons.mode = skip).');
  process.exit(0);
}
// Copies, archived experiments and vendored templates are never deployed, so
// there is no page to give an icon set to.
const unmanagedClassifications = new Set(['duplicate', 'archived', 'template', 'hosted-only']);
if (unmanagedClassifications.has(config.classification) && !icons.mode) {
  console.log('[icons] ' + slug + ': ' + config.classification + ' project, no icon set to manage.');
  process.exit(0);
}

// A project whose head is rendered from code (Next, Nuxt, an Angular service)
// keeps its <link> tags there; this script still renders and checks the files.
const renderedFrom = icons.renderedFrom ?? social.renderedFrom ?? null;
const htmlFile = renderedFrom ? null : (icons.htmlFile ?? social.htmlFile ?? findHtml());
const htmlPath = htmlFile ? path.join(repoRoot, htmlFile) : null;
if (!renderedFrom && (!htmlPath || !fs.existsSync(htmlPath))) {
  if (!curated.deploymentUrl) {
    console.log('[icons] ' + slug + ': not deployed and no page head found; nothing to manage.');
    process.exit(0);
  }
  console.error('[icons] ' + slug + ': no page head found. Set icons.htmlFile in scripts/project-meta.config.mjs.');
  process.exit(1);
}

const outputDirRelative = (icons.outputDir ?? social.staticDir ?? 'public').split(path.sep).join('/');
const outputDir = path.join(repoRoot, outputDirRelative);
const urlPrefix = normalizePrefix(icons.urlPrefix ?? prefixFromImagePath(social.imageUrlPath));
const html = htmlPath ? fs.readFileSync(htmlPath, 'utf8') : '';
const eol = html.includes('\r\n') ? '\r\n' : '\n';

if (mode === 'check') {
  // The project renders its own icons (a PWA build step, a design export). Only
  // make sure the head still links a favicon, an Apple icon and a manifest, and
  // that every one of them exists on disk.
  const problems = [];
  const required = [
    ['favicon', /<link[^>]*rel=["'](?:shortcut )?icon["'][^>]*>/i],
    ['apple-touch-icon', /<link[^>]*rel=["']apple-touch-icon["'][^>]*>/i],
    ['web manifest', /<link[^>]*rel=["']manifest["'][^>]*>/i]
  ];
  for (const [label, pattern] of required) {
    const match = pattern.exec(html);
    if (!match) {
      problems.push('head has no ' + label + ' link');
      continue;
    }
    const href = /href=["']([^"']+)["']/i.exec(match[0])?.[1];
    if (href && !href.startsWith('data:') && !/^https?:/i.test(href) && !fileForHref(href)) {
      problems.push(label + ' points at ' + href + ' which does not exist under ' + outputDirRelative);
    }
  }
  if (problems.length > 0) {
    console.error('[icons] ' + slug + ': ' + problems.join('; '));
    process.exit(1);
  }
  console.log('[icons] ' + slug + ': the project keeps its own icon set and the head links all resolve.');
  process.exit(0);
}

// ------------------------------------------------------------------ generate

const sourceRelative = (icons.source ?? outputDirRelative + '/favicon.svg').split(path.sep).join('/');
const sourcePath = path.join(repoRoot, sourceRelative);
if (!fs.existsSync(sourcePath)) {
  if (!curated.deploymentUrl) {
    console.log('[icons] ' + slug + ': not deployed and no ' + sourceRelative + ' yet; add one to get an icon set.');
    process.exit(0);
  }
  console.error('[icons] ' + slug + ': no source icon at ' + sourceRelative + '. Add an SVG there or set icons.source.');
  process.exit(1);
}
const svg = fs.readFileSync(sourcePath, 'utf8');
// The manifest and the theme-color meta need a colour, and it is a curated
// choice, so there is no default to fall back on.
const themeColor = icons.themeColor ?? curated.accent;
if (!themeColor) {
  console.error('[icons] ' + slug + ': set icons.themeColor (or curated.accent) in scripts/project-meta.config.mjs.');
  process.exit(1);
}
const background = icons.background ?? themeColor;
// The rendered pixels depend on the SVG and on the fill behind the padded
// icons, so both go into the key that decides whether a re-render is due.
// Line endings are normalised first, so a CRLF checkout of the same SVG does
// not read as a change.
const sourceHash = createHash('sha256').update(svg.replace(/\r\n/g, '\n') + '\n' + background).digest('hex').slice(0, 16);
const name = icons.name ?? curated.title ?? slug;
const shortName = icons.shortName ?? (name.length <= 12 ? name : name.split(/[\s:-]+/)[0]);
const description = icons.description ?? curated.description ?? curated.subtitle ?? '';

const files = {
  'favicon.ico': { sizes: [16, 32, 48], kind: 'ico' },
  'apple-touch-icon.png': { size: 180, kind: 'png', fill: background, scale: 1 },
  'icon-192.png': { size: 192, kind: 'png', scale: 1 },
  'icon-512.png': { size: 512, kind: 'png', scale: 1 },
  'icon-maskable-512.png': { size: 512, kind: 'png', fill: background, scale: 0.8 }
};
const manifestName = icons.manifestName ?? 'site.webmanifest';
const recordPath = path.join(repoRoot, 'project-media', 'icons.json');

// icons.manifest in the config adds to or overrides these fields (a game wants
// display: 'fullscreen', categories, screenshots).
const manifest = {
  name,
  short_name: shortName,
  description,
  start_url: urlPrefix,
  scope: urlPrefix,
  display: 'standalone',
  background_color: background,
  theme_color: themeColor,
  icons: [
    { src: urlPrefix + 'icon-192.png', sizes: '192x192', type: 'image/png' },
    { src: urlPrefix + 'icon-512.png', sizes: '512x512', type: 'image/png' },
    { src: urlPrefix + 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' }
  ],
  ...(icons.manifest ?? {})
};
const manifestJson = JSON.stringify(manifest, null, 2) + '\n';

const links = [
  '<link rel="icon" type="image/svg+xml" href="' + urlPrefix + 'favicon.svg" />',
  '<link rel="icon" type="image/x-icon" href="' + urlPrefix + 'favicon.ico" sizes="16x16 32x32 48x48" />',
  '<link rel="apple-touch-icon" sizes="180x180" href="' + urlPrefix + 'apple-touch-icon.png" />',
  '<link rel="manifest" href="' + urlPrefix + manifestName + '" />'
];
const nextHtml = htmlPath ? renderHead(html) : html;

const record = readJson(recordPath);
const expectedFiles = [...Object.keys(files), 'favicon.svg', manifestName];
const outputsMissing = expectedFiles.filter((file) => !fs.existsSync(path.join(outputDir, file)));
const sourceChanged = record?.sourceHash !== sourceHash;
const manifestPath = path.join(outputDir, manifestName);
const manifestStale = !fs.existsSync(manifestPath) ||
  normalizeJson(fs.readFileSync(manifestPath, 'utf8')) !== normalizeJson(manifestJson);

if (checkOnly) {
  const problems = [];
  if (nextHtml !== html) problems.push('head icon links are out of date');
  if (outputsMissing.length > 0) problems.push('missing ' + outputsMissing.join(', '));
  else if (sourceChanged) problems.push(sourceRelative + ' changed since the icons were rendered');
  if (manifestStale) problems.push(manifestName + ' is out of date');
  if (problems.length > 0) {
    console.error('[icons] ' + slug + ': ' + problems.join('; ') + ' (run: npm run icons)');
    process.exit(1);
  }
  console.log('[icons] ' + slug + ': icon set and head links are up to date.');
  process.exit(0);
}

fs.mkdirSync(outputDir, { recursive: true });
const rendered = [];

if (outputsMissing.some((file) => files[file]) || sourceChanged) {
  const chromium = await loadChromium();
  const browser = await chromium.launch({ headless: true });
  try {
    for (const [file, spec] of Object.entries(files)) {
      const target = path.join(outputDir, file);
      if (spec.kind === 'ico') {
        const entries = [];
        for (const size of spec.sizes) entries.push({ size, png: await renderPng(browser, size, spec) });
        fs.writeFileSync(target, encodeIco(entries));
      } else {
        fs.writeFileSync(target, await renderPng(browser, spec.size, spec));
      }
      rendered.push(file);
    }
  } finally {
    await browser.close();
  }
}

const svgTarget = path.join(outputDir, 'favicon.svg');
const svgIsSource = path.resolve(svgTarget) === path.resolve(sourcePath);
if (!svgIsSource && (!fs.existsSync(svgTarget) || fs.readFileSync(svgTarget, 'utf8') !== svg)) {
  fs.writeFileSync(svgTarget, svg);
  rendered.push('favicon.svg');
}
if (manifestStale) {
  fs.writeFileSync(manifestPath, manifestJson);
  rendered.push(manifestName);
}

fs.mkdirSync(path.dirname(recordPath), { recursive: true });
const keepStamp = record?.sourceHash === sourceHash && rendered.length === 0 && record?.renderedAt;
fs.writeFileSync(recordPath, JSON.stringify({
  slug,
  source: sourceRelative,
  sourceHash,
  outputDir: outputDirRelative,
  urlPrefix,
  renderedAt: keepStamp ? record.renderedAt : new Date().toISOString(),
  files: expectedFiles
}, null, 2) + '\n');

if (renderedFrom) {
  console.log('[icons] ' + slug + ': the head is rendered from ' + renderedFrom + ' - link ' + urlPrefix + 'favicon.svg, ' +
    urlPrefix + 'favicon.ico, ' + urlPrefix + 'apple-touch-icon.png and ' + urlPrefix + manifestName + ' there.');
} else if (nextHtml !== html) {
  fs.writeFileSync(htmlPath, nextHtml);
  console.log('[icons] ' + slug + ': updated icon links in ' + htmlFile);
}
console.log('[icons] ' + slug + ': ' + (rendered.length > 0 ? 'wrote ' + rendered.join(', ') : 'icon set already current') +
  ' in ' + outputDirRelative + '/');

// ------------------------------------------------------------------ rendering

async function renderPng(browser, size, spec) {
  const scale = spec.scale ?? 1;
  const inner = Math.round(size * scale);
  const offset = Math.round((size - inner) / 2);
  const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
  try {
    await page.setContent(
      '<!doctype html><html><head><style>' +
      'html,body{margin:0;padding:0;width:' + size + 'px;height:' + size + 'px;overflow:hidden;background:' + (spec.fill ?? 'transparent') + ';}' +
      '.icon{position:absolute;left:' + offset + 'px;top:' + offset + 'px;width:' + inner + 'px;height:' + inner + 'px;}' +
      '.icon svg{display:block;width:100%;height:100%;}' +
      '</style></head><body><div class="icon">' + svg + '</div></body></html>'
    );
    await page.evaluate('document.fonts ? document.fonts.ready : null');
    return await page.screenshot({ type: 'png', omitBackground: !spec.fill, clip: { x: 0, y: 0, width: size, height: size } });
  } finally {
    await page.close();
  }
}

// An ICO is a small directory of images. PNG-encoded entries are understood by
// every current browser, so no BMP conversion is needed.
function encodeIco(entries) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(entries.length, 4);
  const directory = [];
  const images = [];
  let offset = 6 + entries.length * 16;
  for (const { size, png } of entries) {
    const entry = Buffer.alloc(16);
    entry.writeUInt8(size >= 256 ? 0 : size, 0);
    entry.writeUInt8(size >= 256 ? 0 : size, 1);
    entry.writeUInt8(0, 2);
    entry.writeUInt8(0, 3);
    entry.writeUInt16LE(1, 4);
    entry.writeUInt16LE(32, 6);
    entry.writeUInt32LE(png.length, 8);
    entry.writeUInt32LE(offset, 12);
    directory.push(entry);
    images.push(png);
    offset += png.length;
  }
  return Buffer.concat([header, ...directory, ...images]);
}

// ------------------------------------------------------------------ head

function renderHead(source) {
  const indent = detectHeadIndent(source);
  const hasThemeColor = /<meta[^>]*name=["']theme-color["']/i.test(stripBlock(source));
  const lines = [START, ...links];
  if (!hasThemeColor) lines.push('<meta name="theme-color" content="' + themeColor + '" />');
  lines.push(END);
  const block = lines.map((line) => indent + line).join(eol);

  if (source.includes(START) && source.includes(END)) {
    // A repo's formatter may re-wrap the block (one attribute per line); that
    // is the same markup, so leave its formatting alone.
    const existing = source.slice(source.indexOf(START), source.indexOf(END) + END.length);
    if (normalizeMarkup(existing) === normalizeMarkup(block)) return source;
    return source.slice(0, source.indexOf(START)) + block.trimStart() + source.slice(source.indexOf(END) + END.length);
  }

  // Any loose icon links the page carried before are superseded by the block.
  // A tag is matched attribute by attribute, so an inline data: URI holding a
  // literal ">" inside its quotes does not end the match early.
  const attribute = String.raw`(?:[^>"']|"[^"]*"|'[^']*')*`;
  const rels = `(?:shortcut icon|icon|apple-touch-icon|manifest)`;
  const looseLink = new RegExp(String.raw`[ \t]*<link\b` + attribute + String.raw`\brel=["']` + rels + `["']` + attribute + String.raw`>[ \t]*\r?\n?`, 'gi');
  let next = source.replace(looseLink, '');
  const anchor = next.search(/[ \t]*<title[\s>]/i);
  if (anchor !== -1) {
    return next.slice(0, anchor) + block + eol + next.slice(anchor);
  }
  const headClose = next.search(/<\/head>/i);
  if (headClose === -1) {
    console.error('[icons] ' + slug + ': ' + htmlFile + ' has no </head> to insert into.');
    process.exit(1);
  }
  return next.slice(0, headClose) + block.trimStart() + eol + indent + next.slice(headClose);
}

function normalizeMarkup(text) {
  return text.replace(/\s+/g, ' ').replace(/\s*\/>/g, ' />').trim();
}

function stripBlock(source) {
  if (!source.includes(START) || !source.includes(END)) return source;
  return source.slice(0, source.indexOf(START)) + source.slice(source.indexOf(END) + END.length);
}

// A head whose tags start at column 0 gets an unindented block.
function detectHeadIndent(source) {
  const match = /\n([ \t]*)<(?:meta|link|title)/i.exec(source);
  return match ? match[1] : '    ';
}

// ------------------------------------------------------------------ helpers

function findHtml() {
  return ['index.html', 'app/index.html', 'src/index.html', 'public/index.html'].find((relative) =>
    fs.existsSync(path.join(repoRoot, relative)));
}

function prefixFromImagePath(imageUrlPath) {
  if (!imageUrlPath) return '/';
  return imageUrlPath.slice(0, imageUrlPath.lastIndexOf('/') + 1) || '/';
}

function normalizePrefix(prefix) {
  let value = String(prefix || '/');
  if (!value.endsWith('/')) value += '/';
  return value;
}

function fileForHref(href) {
  const clean = href.split('?')[0].split('#')[0];
  const relative = clean.startsWith(urlPrefix) ? clean.slice(urlPrefix.length) : clean.replace(/^\.?\//, '');
  const candidates = [path.join(outputDir, relative), path.join(repoRoot, relative)];
  return candidates.find((candidate) => fs.existsSync(candidate));
}

function normalizeJson(text) {
  try {
    return JSON.stringify(JSON.parse(text));
  } catch {
    return text;
  }
}

function readJson(filePath) {
  if (!fs.existsSync(filePath)) return null;
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } catch {
    return null;
  }
}

async function loadChromium() {
  const candidates = [repoRoot];
  if (process.env.PORTFOLIO_ROOT) candidates.push(process.env.PORTFOLIO_ROOT);
  const portfolioRoot = config.media?.sourceDir ? path.resolve(config.media.sourceDir, '..', '..', '..', '..') : null;
  if (portfolioRoot) candidates.push(portfolioRoot);

  for (const base of candidates) {
    for (const packageName of ['@playwright/test', 'playwright', 'playwright-core']) {
      try {
        const require_ = createRequire(path.join(base, 'package.json'));
        const resolved = require_.resolve(packageName);
        const module_ = await import(pathToFileURL(resolved).href);
        const chromium_ = module_.chromium ?? module_.default?.chromium;
        if (chromium_) return chromium_;
      } catch {
        // try the next candidate
      }
    }
  }
  console.error('[icons] Playwright not found. Install it here (npm i -D @playwright/test && npx playwright install chromium)');
  console.error('        or set PORTFOLIO_ROOT to a checkout that has it.');
  process.exit(2);
}
